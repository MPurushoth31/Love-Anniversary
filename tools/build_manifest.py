#!/usr/bin/env python3
"""Build photo/song manifests from original folders, without thumbnails.

Features:
- Recursively scans photos/journey, photos/moments, photos/surprise.
- Detects exact and very-close visual duplicates within each folder.
- Keeps the highest-resolution copy and writes a duplicate report.
- Migrates old manifest metadata to the actual file when extensions differ.
- Keeps metadata for photos not present in a partial project ZIP; the browser
  only renders paths listed in photo-assets.js, so missing records never create
  empty frames.
- Never creates photos/thumbs/.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PHOTO_ROOT = ROOT / "photos"
IMAGE_EXTS = {".webp", ".jpg", ".jpeg", ".png", ".avif"}
AUDIO_EXTS = {".mp3", ".m4a", ".aac", ".ogg", ".wav", ".opus"}
MOOD_ORDER = {"happy": 0, "funny": 1, "unforget": 2}
YEAR_RE = re.compile(r"(?<!\d)(201[6-9]|202[0-6])(?!\d)")
MOOD_RE = re.compile(r"(?<![a-z])(happy|funny|unforget)(?![a-z])", re.I)
PHASH_DISTANCE_LIMIT = 2
ASPECT_RATIO_TOLERANCE = 0.015
PIXEL_MAE_LIMIT = 5.0

try:
    from PIL import Image, ImageOps
except Exception:
    Image = ImageOps = None


def js_write(relative: str, variable: str, payload) -> None:
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"/* Generated by tools/build_manifest.py. Do not edit by hand. */\n"
        f"window.{variable}=" + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )


def all_images(folder: Path) -> list[Path]:
    """Recursively return original images; ignore old thumbnail directories."""
    folder.mkdir(parents=True, exist_ok=True)
    files = []
    for path in folder.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in IMAGE_EXTS:
            continue
        relative_parts = [part.casefold() for part in path.relative_to(PHOTO_ROOT).parts]
        if any(part in {"thumbs", "thumbnails"} for part in relative_parts):
            continue
        files.append(path)
    return sorted(files, key=lambda p: natural_key(p.relative_to(folder).as_posix()))


def image_path(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def image_size(path: Path) -> tuple[int, int]:
    if Image is None:
        return 1, 1
    try:
        with Image.open(path) as source:
            image = ImageOps.exif_transpose(source) if ImageOps else source
            width, height = image.size
            return max(1, int(width)), max(1, int(height))
    except Exception:
        return 1, 1


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


# A small pure-Python pHash keeps Pillow as the only optional dependency.
# Comparing only very low-frequency coefficients (distance <= 3) is strict
# enough to catch resized/re-encoded copies without merging ordinary photo bursts.
_PHASH_COS = None

def perceptual_signature(path: Path) -> tuple[int | None, float | None, bytes | None]:
    """Return pHash + normalized RGB pixels for a conservative visual match."""
    global _PHASH_COS
    if Image is None:
        return None, None, None
    try:
        with Image.open(path) as source:
            image = ImageOps.exif_transpose(source) if ImageOps else source
            width, height = image.size
            ratio = width / max(1, height)
            gray = image.convert("L").resize((32, 32), Image.Resampling.LANCZOS)
            pixels = list(gray.get_flattened_data() if hasattr(gray, "get_flattened_data") else gray.getdata())
            rgb = image.convert("RGB")
            target_width = 64
            target_height = max(16, round(target_width / ratio))
            rgb = rgb.resize((target_width, target_height), Image.Resampling.LANCZOS)
            rgb_data = rgb.get_flattened_data() if hasattr(rgb, "get_flattened_data") else rgb.getdata()
            rgb_values = rgb.tobytes()
        if _PHASH_COS is None:
            _PHASH_COS = [
                [math.cos((2 * position + 1) * frequency * math.pi / 64)
                 for frequency in range(8)]
                for position in range(32)
            ]
        coefficients = []
        for u in range(8):
            for v in range(8):
                if u == 0 and v == 0:
                    continue
                total = 0.0
                for y in range(32):
                    row_offset = y * 32
                    cy = _PHASH_COS[y][v]
                    for x in range(32):
                        total += pixels[row_offset + x] * _PHASH_COS[x][u] * cy
                coefficients.append(total)
        median = sorted(coefficients)[len(coefficients) // 2]
        value = 0
        for coefficient in coefficients:
            value = (value << 1) | int(coefficient > median)
        return value, ratio, rgb_values
    except Exception:
        return None, None, None


def pixel_mae(a: bytes, b: bytes) -> float:
    if len(a) != len(b) or not a:
        return float("inf")
    return sum(abs(x - y) for x, y in zip(a, b)) / len(a)


def hamming_distance(a: int, b: int) -> int:
    return (a ^ b).bit_count()


def natural_key(value: str):
    return tuple(
        (0, int(part)) if part.isdigit() else (1, part.casefold())
        for part in re.split(r"(\d+)", value)
        if part != ""
    )


def keeper_key(path: Path, bucket: Path, bucket_name: str):
    width, height = image_size(path)
    try:
        size = path.stat().st_size
    except OSError:
        size = 0
    year = year_from(path, bucket)
    # Keep the earliest dated occurrence when the same photo was copied into
    # multiple years. For Journey, always prefer a dated chapter photo over a
    # yearless extra such as thaali. Resolution/bytes break ties within a year.
    if bucket_name == "journey":
        date_key = (0, int(year)) if year else (1, 9999)
    elif bucket_name == "moments":
        date_key = (0, int(year)) if year else (1, 9999)
    else:
        date_key = (0, 0)
    return (date_key, -(width * height), -size, natural_key(path.relative_to(bucket).as_posix()))


def deduplicate_images(paths: list[Path], bucket_name: str) -> tuple[list[Path], dict[str, str], list[dict]]:
    """Deduplicate exact bytes and near-identical visual copies within a bucket.

    The higher-quality original is retained. Aliases are recorded for Journey
    references, while Moments duplicate cards are removed rather than remapped
    to a second frame.
    """
    if len(paths) < 2:
        return paths, {}, []

    info = {}
    for path in paths:
        try:
            sha = file_sha256(path)
        except OSError:
            sha = ""
        phash, ratio, pixels = perceptual_signature(path)
        info[path] = {"sha": sha, "phash": phash, "ratio": ratio, "pixels": pixels}

    bucket = PHOTO_ROOT / bucket_name
    ranked = sorted(paths, key=lambda path: keeper_key(path, bucket, bucket_name))
    kept: list[Path] = []
    aliases: dict[str, str] = {}
    duplicates: list[dict] = []

    for candidate in ranked:
        match = None
        match_type = None
        distance = None
        for canonical in kept:
            a, b = info[candidate], info[canonical]
            if a["sha"] and a["sha"] == b["sha"]:
                match, match_type, distance = canonical, "exact_sha256", 0
                break
            if a["phash"] is None or b["phash"] is None:
                continue
            if a["ratio"] is None or b["ratio"] is None:
                continue
            ratio_gap = abs(a["ratio"] - b["ratio"]) / max(a["ratio"], b["ratio"], 0.001)
            if ratio_gap > ASPECT_RATIO_TOLERANCE:
                continue
            d = hamming_distance(a["phash"], b["phash"])
            if d <= PHASH_DISTANCE_LIMIT and a["pixels"] is not None and b["pixels"] is not None:
                mae = pixel_mae(a["pixels"], b["pixels"])
                if mae <= PIXEL_MAE_LIMIT:
                    match, match_type, distance = canonical, "perceptual_and_pixel", d
                    break
        if match is None:
            kept.append(candidate)
        else:
            aliases[image_path(candidate)] = image_path(match)
            duplicates.append({
                "folder": bucket_name,
                "kept": image_path(match),
                "removed": image_path(candidate),
                "match": match_type,
                "distance": distance,
            })

    kept.sort(key=lambda p: natural_key(p.relative_to(PHOTO_ROOT).as_posix()))
    duplicates.sort(key=lambda row: natural_key(row["removed"]))
    return kept, aliases, duplicates


def year_from(path: Path, bucket: Path) -> str | None:
    relative = path.relative_to(bucket)
    match = YEAR_RE.search(path.stem)
    if match:
        return match.group(1)
    for part in relative.parts[:-1]:
        match = YEAR_RE.search(part)
        if match:
            return match.group(1)
    return None


def mood_from(path: Path, bucket: Path) -> str:
    match = MOOD_RE.search(path.stem)
    if not match:
        match = MOOD_RE.search(path.relative_to(bucket).as_posix())
    return match.group(1).lower() if match else "happy"


def captions_for(bucket: Path) -> dict[str, str]:
    captions: dict[str, str] = {}
    if not bucket.exists():
        return captions
    for caption_file in sorted(bucket.rglob("captions.txt")):
        parent = caption_file.parent
        try:
            lines = caption_file.read_text(encoding="utf-8-sig").splitlines()
        except OSError:
            continue
        for line in lines:
            match = re.match(r"^\s*(.+?)\s*[–—-]\s*(.+?)\s*$", line)
            if not match:
                continue
            key, value = match.group(1).strip().replace("\\", "/"), match.group(2).strip()
            captions[key.lower()] = value
            captions[Path(key).name.lower()] = value
            captions[Path(key).stem.lower()] = value
            rel_parent = parent.relative_to(bucket).as_posix()
            if rel_parent != ".":
                captions[f"{rel_parent}/{key}".lower()] = value
    return captions


def caption_is_explicit(path: Path, bucket: Path, captions: dict[str, str]) -> bool:
    relative = path.relative_to(bucket).as_posix()
    return any(key in captions for key in (relative.lower(), path.name.lower(), path.stem.lower()))


def caption_for(path: Path, bucket: Path, captions: dict[str, str]) -> str:
    relative = path.relative_to(bucket).as_posix()
    for key in (relative.lower(), path.name.lower(), path.stem.lower()):
        if key in captions:
            return captions[key]
    return re.sub(r"[_-]+", " ", path.stem).strip() or "A little memory ❤️"


def unique_key(path: Path, bucket: Path) -> str:
    raw = path.relative_to(bucket).as_posix().casefold()
    return re.sub(r"[^a-z0-9_-]+", "_", raw).strip("_") or "memory"


def best_same_stem(items: list[dict]) -> dict:
    def score(item):
        width, height = int(item.get("w", 1) or 1), int(item.get("h", 1) or 1)
        path = str(item.get("f", ""))
        ext = Path(path).suffix.lower()
        ext_rank = {".webp": 0, ".jpg": 1, ".jpeg": 2, ".png": 3, ".avif": 4}.get(ext, 9)
        return (width * height, -ext_rank, path.casefold())
    return max(items, key=score)


def build_photo_assets(images_by_bucket: dict[str, list[Path]]) -> tuple[list[str], list[dict]]:
    all_paths: list[str] = []
    journey_items: list[dict] = []
    journey_root = PHOTO_ROOT / "journey"
    for bucket_name in ("journey", "moments", "surprise"):
        bucket = PHOTO_ROOT / bucket_name
        captions = captions_for(bucket) if bucket_name == "journey" else {}
        for path in images_by_bucket[bucket_name]:
            all_paths.append(image_path(path))
            if bucket_name == "journey":
                year = year_from(path, bucket)
                if year:
                    width, height = image_size(path)
                    journey_items.append({
                        "y": year, "f": image_path(path), "w": width, "h": height,
                        "c": caption_for(path, bucket, captions),
                        "_caption_explicit": caption_is_explicit(path, bucket, captions),
                    })
    journey_items.sort(key=lambda item: (int(item["y"]), natural_key(item["f"])))
    return sorted(set(all_paths), key=natural_key), journey_items


def build_moments(images_by_bucket: dict[str, list[Path]]) -> list[dict]:
    bucket = PHOTO_ROOT / "moments"
    captions = captions_for(bucket)
    output, skipped = [], []
    for path in images_by_bucket["moments"]:
        year = year_from(path, bucket)
        if not year:
            skipped.append(path.relative_to(bucket).as_posix())
            continue
        width, height = image_size(path)
        mood = mood_from(path, bucket)
        number_match = re.search(r"(\d+)$", path.stem)
        output.append({
            "k": unique_key(path, bucket), "f": image_path(path),
            "w": width, "h": height, "c": caption_for(path, bucket, captions),
            "_caption_explicit": caption_is_explicit(path, bucket, captions),
            "y": year, "m": mood, "n": int(number_match.group(1)) if number_match else 0,
        })
    output.sort(key=lambda item: (item["y"], MOOD_ORDER.get(item["m"], 9), item["n"], item["f"].casefold()))
    for item in output:
        item.pop("n", None)
    if skipped:
        print(f"Moments files without a recognizable year: {len(skipped)} (not shown in the year archive)")
        for name in skipped[:10]:
            print("  -", name)
    return output


def build_surprise(images_by_bucket: dict[str, list[Path]]) -> list[dict]:
    bucket = PHOTO_ROOT / "surprise"
    captions = captions_for(bucket)
    output = []
    for path in images_by_bucket["surprise"]:
        width, height = image_size(path)
        output.append({
            "k": unique_key(path, bucket), "f": image_path(path),
            "w": width, "h": height, "c": caption_for(path, bucket, captions),
            "_caption_explicit": caption_is_explicit(path, bucket, captions),
        })
    return output


def load_existing_js_array(relative: str, variable: str) -> list[dict]:
    path = ROOT / relative
    if not path.exists():
        return []
    try:
        source = path.read_text(encoding="utf-8")
        match = re.search(rf"window\.{re.escape(variable)}\s*=\s*(\[.*?\])\s*;", source, re.S)
        if not match:
            return []
        value = json.loads(match.group(1))
        return value if isinstance(value, list) else []
    except (OSError, json.JSONDecodeError):
        return []


def preserve_missing_records(relative: str, variable: str, generated: list[dict],
                             physically_present_paths: set[str], sort_key) -> list[dict]:
    """Preserve old captions/metadata without creating stale visible photo cards.

    If a real file with the same stem exists (e.g. old .webp -> actual .jpg),
    move the metadata to the best actual file instead of keeping an orphan path.
    If no file currently exists, retain the old record for future restoration;
    the runtime filters it out because it is absent from PHOTO_ASSETS.
    """
    old_records = load_existing_js_array(relative, variable)
    if not old_records:
        return sorted(generated, key=sort_key)

    old_by_path = {item.get("f"): item for item in old_records if isinstance(item, dict) and item.get("f")}
    old_by_stem: dict[str, list[dict]] = {}
    new_by_stem: dict[str, list[dict]] = {}
    for item in old_records:
        if isinstance(item, dict) and item.get("f"):
            old_by_stem.setdefault(Path(item["f"]).stem.casefold(), []).append(item)
    for item in generated:
        if item.get("f"):
            new_by_stem.setdefault(Path(item["f"]).stem.casefold(), []).append(item)

    migrated: dict[str, dict] = {}
    orphans: dict[str, dict] = {}
    for old_path, old_item in old_by_path.items():
        if old_path in physically_present_paths:
            continue  # exact actual file will be generated below
        candidates = new_by_stem.get(Path(old_path).stem.casefold(), [])
        if candidates:
            candidate = best_same_stem(candidates)
            migrated.setdefault(candidate["f"], old_item)
        else:
            # Keep metadata for a project ZIP that does not contain source photos.
            # The browser will not render this record until a matching asset exists.
            orphans[old_path] = old_item

    merged: dict[str, dict] = dict(orphans)
    for item in generated:
        path = item.get("f")
        if not path:
            continue
        item = dict(item)
        previous = old_by_path.get(path) or migrated.get(path)
        if previous and previous.get("c") and not item.get("_caption_explicit"):
            item["c"] = previous["c"]
        item.pop("_caption_explicit", None)
        merged[path] = item
    return sorted(merged.values(), key=sort_key)


def build_songs() -> dict[str, list[str]]:
    songs_root = ROOT / "songs"
    songs_root.mkdir(parents=True, exist_ok=True)
    output = {}
    for directory in sorted(p for p in songs_root.iterdir() if p.is_dir()):
        files = sorted(p for p in directory.rglob("*") if p.is_file() and p.suffix.lower() in AUDIO_EXTS)
        output[directory.name] = [
            "/".join(quote(part, safe="-_.~()") for part in p.relative_to(ROOT).as_posix().split("/"))
            for p in files
        ]
    return output


def main() -> None:
    for name in ("journey", "moments", "surprise"):
        (PHOTO_ROOT / name).mkdir(parents=True, exist_ok=True)

    raw_by_bucket = {name: all_images(PHOTO_ROOT / name) for name in ("journey", "moments", "surprise")}
    images_by_bucket: dict[str, list[Path]] = {}
    alias_map: dict[str, str] = {}
    duplicate_report: list[dict] = []
    duplicate_counts = {}
    for name, paths in raw_by_bucket.items():
        unique, aliases, duplicates = deduplicate_images(paths, name)
        images_by_bucket[name] = unique
        if name == "journey":
            alias_map.update(aliases)
        duplicate_report.extend(duplicates)
        duplicate_counts[name] = {"source_files": len(paths), "unique_files": len(unique), "duplicates_removed": len(duplicates)}

    assets, journey_items = build_photo_assets(images_by_bucket)
    moments = build_moments(images_by_bucket)
    surprise = build_surprise(images_by_bucket)
    songs = build_songs()

    present_journey = {image_path(p) for p in raw_by_bucket["journey"]}
    present_moments = {image_path(p) for p in raw_by_bucket["moments"]}
    present_surprise = {image_path(p) for p in raw_by_bucket["surprise"]}

    journey_items = preserve_missing_records(
        "data/journey-photos.js", "JOURNEY_PHOTOS", journey_items, present_journey,
        lambda item: (int(item.get("y", 0) or 0), natural_key(str(item.get("f", "")))),
    )
    moments = preserve_missing_records(
        "data/moments.js", "MOMENTS", moments, present_moments,
        lambda item: (int(item.get("y", 0) or 0), MOOD_ORDER.get(item.get("m", ""), 9), natural_key(str(item.get("f", "")))),
    )
    surprise = preserve_missing_records(
        "data/surprise.js", "SURPRISE", surprise, present_surprise,
        lambda item: natural_key(str(item.get("f", ""))),
    )

    js_write("data/photo-assets.js", "PHOTO_ASSETS", assets)
    js_write("data/photo-aliases.js", "PHOTO_ALIASES", alias_map)
    js_write("data/journey-photos.js", "JOURNEY_PHOTOS", journey_items)
    js_write("data/moments.js", "MOMENTS", moments)
    js_write("data/surprise.js", "SURPRISE", surprise)
    js_write("data/songs.js", "SONGS", songs)
    (ROOT / "data/photo-duplicates.json").write_text(
        json.dumps({"summary": duplicate_counts, "duplicates": duplicate_report}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    print("\nPHOTO FOLDER AUDIT")
    for name in ("journey", "moments", "surprise"):
        row = duplicate_counts[name]
        print(f"{name.capitalize():9} {row['source_files']:>3} source photos → {row['unique_files']:>3} unique; {row['duplicates_removed']} duplicate copies excluded from the website")
    journey_dated = sum(1 for path in images_by_bucket["journey"] if year_from(path, PHOTO_ROOT / "journey"))
    journey_yearless = len(images_by_bucket["journey"]) - journey_dated
    print(f"Journey year-tagged timeline photos: {journey_dated}; yearless photos: {journey_yearless} (not placed on the year timeline)")
    print(f"Total original image paths indexed: {len(assets)}")
    active_moment_paths = set(path for path in assets if path.startswith("photos/moments/"))
    active_moment_records = sum(1 for item in moments if item.get("f") in active_moment_paths)
    legacy_hidden_records = max(0, len(moments) - active_moment_records)
    print(f"Moments active frames: {active_moment_records}; unmatched legacy metadata hidden from the page: {legacy_hidden_records}")
    print("Duplicate details saved to data/photo-duplicates.json")
    if Image is None:
        print("WARNING: Pillow is unavailable; only byte-identical duplicate files could be detected.")
    print("No thumbnails created. Original photos are used directly.")


if __name__ == "__main__":
    main()
